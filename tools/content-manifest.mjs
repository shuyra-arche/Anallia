#!/usr/bin/env node
/**
 * Generate the production manifest, search index, compatibility rows and the
 * per-hub dynamic content parts from src/content/author/*.json.
 *
 * Usage:
 *   node tools/content-manifest.mjs
 *   node tools/content-manifest.mjs --check
 */
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";

const root = new URL("../", import.meta.url).pathname;
const authorDir = join(root, "src/content/author");
const outputDir = join(root, "src/content/generated");
const checkOnly = process.argv.includes("--check");

const stripReferences = (text) =>
  text.replace(/\{([^{}|]+)\|[^{}]+\}/g, "$1");

const normalize = (text) => stripReferences(text);

const referenceTargets = (text) =>
  [...text.matchAll(/\{([^{}|]+)\|([^{}]+)\}/g)]
    .map((match) => match[2])
    .filter((target) => !target.startsWith("act:"));

const definitions = JSON.parse(
  await readFile(join(authorDir, "hubs.json"), "utf8"),
);
const rows = {};
const chapters = [];
const searchIndex = [];
const parts = {};
const written = new Map();

for (const definition of definitions) {
  const hub = definition.id;
  const content = JSON.parse(
    await readFile(join(authorDir, `${hub}.json`), "utf8"),
  );
  rows[hub] = content;
  const part = {};
  for (const row of content) {
    const [id, name, parent, title, circle, line, refs] = row;
    part[id] = { circle, line };
    chapters.push({
      id,
      name,
      parent,
      title,
      hub,
      refs: refs.map(([glyph, target]) => ({ glyph, target })),
      inlineTargets: [
        ...new Set([
          ...referenceTargets(circle),
          ...referenceTargets(line),
        ]),
      ],
    });
    if (definition.kind !== "search") {
      const circleText = normalize(circle);
      const lineText = normalize(line);
      searchIndex.push({
        sourceId: id,
        searchText: `${circleText} ${lineText}`,
        circleStart: 0,
        circleEnd: circleText.length,
        lineStart: circleText.length + 1,
        lineEnd: circleText.length + 1 + lineText.length,
      });
    }
  }
  parts[hub] = part;
}

const json = (value) => JSON.stringify(value, null, 2);

written.set(
  "hubs.ts",
  `// Generated by tools/content-manifest.mjs. Do not edit by hand.
import type { HubDefinition } from "../../core/types.ts";

export const hubDefinitions: HubDefinition[] = ${json(definitions)};
`,
);

written.set(
  "search-index.ts",
  `// Generated by tools/content-manifest.mjs. Do not edit by hand.
import type { SearchIndexEntry } from "../../core/content.ts";

export const initialSearchIndex: SearchIndexEntry[] = ${json(searchIndex)};
`,
);

written.set(
  "manifest.ts",
  `// Generated by tools/content-manifest.mjs. Do not edit by hand.
import type { ContentManifest } from "../../core/content.ts";
import { hubDefinitions } from "./hubs.ts";
import { initialSearchIndex } from "./search-index.ts";

export { hubDefinitions };

export const contentManifest: ContentManifest = {
  format: 1,
  definitions: hubDefinitions,
  chapters: ${json(chapters)},
  searchIndex: initialSearchIndex,
};
`,
);

written.set(
  "raw.ts",
  `// Generated by tools/content-manifest.mjs. Test compatibility only.
// The production entry should use contentManifest + LocalContentSource.
import type { ContentRow } from "../../core/types.ts";

export const rawContent: Record<string, ContentRow[]> = ${json(rows)};
`,
);

for (const definition of definitions) {
  const hub = definition.id;
  written.set(
    `parts/${hub}.ts`,
    `// Generated by tools/content-manifest.mjs. Loaded on demand.
import type { ContentPart } from "../../types.ts";

export const contentPart: ContentPart = ${json(parts[hub])};
export default contentPart;
`,
  );
}

written.set(
  "part-loaders.ts",
  `// Generated by tools/content-manifest.mjs. No static body imports.
import type { ContentPartLoaders } from "../types.ts";

export const contentPartLoaders: ContentPartLoaders = {
${definitions
  .map(
    (definition) =>
      `  ${JSON.stringify(definition.id)}: () => import("./parts/${definition.id}.ts").then((module) => module.contentPart),`,
  )
  .join("\n")}
};
`,
);

let stale = false;
for (const [name, content] of written) {
  const path = join(outputDir, name);
  if (checkOnly) {
    let existing = "";
    try {
      existing = await readFile(path, "utf8");
    } catch {
      stale = true;
      console.error(`missing ${path}`);
      continue;
    }
    if (existing !== content) {
      stale = true;
      console.error(`stale ${path}`);
    }
    continue;
  }
  await mkdir(dirname(path), { recursive: true });
  await writeFile(path, content);
}

if (checkOnly) {
  if (stale) process.exitCode = 1;
  else console.log("Content manifest is up to date.");
} else {
  console.log(
    `Generated ${written.size} content files for ${chapters.length} chapters and ${searchIndex.length} search entries.`,
  );
}
